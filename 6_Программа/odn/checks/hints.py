    (r"ДУБЛЬ КАНАЛА", "Один канал модуля занят двумя линиями. Исправить: канал в «Однолинейке» N."),
    (r"дубль клеммы", "Номер клеммы повторяется в щите — на схеме две линии на одной клемме. Исправить: клемма "
                      "в «Однолинейке» P (или «+» в автомате E — продолжение группы)."),
