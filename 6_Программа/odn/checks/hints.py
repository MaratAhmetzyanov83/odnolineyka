_RX = [(re.compile(p, re.I), t) for p, t in HINTS]


def hint_for(text: str, rule_doc: str = "") -> str:
    out = []
    for part in re.split(r";\s*", text or ""):
        h = next((t for rx, t in _RX if rx.search(part)), "")
        if h and h not in out:
            out.append(h)
    if not out and rule_doc:
        out.append(" ".join(rule_doc.split()))
    return "\n".join(out)
