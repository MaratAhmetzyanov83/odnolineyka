def excel():
    import win32com.client
    import win32process
    app = win32com.client.DispatchEx("Excel.Application")
    app.Visible = False
    app.DisplayAlerts = False
    app.AskToUpdateLinks = False
    app.AutomationSecurity = 3
    return app, win32process.GetWindowThreadProcessId(app.Hwnd)[1]


def unprotect(ws):
    if not ws.ProtectContents:
        return None
    p = ws.Protection
    opts = dict(DrawingObjects=True, Contents=True, Scenarios=True,
                AllowFormattingCells=p.AllowFormattingCells, AllowFormattingColumns=p.AllowFormattingColumns,
                AllowFormattingRows=p.AllowFormattingRows, AllowSorting=p.AllowSorting,
                AllowFiltering=p.AllowFiltering, AllowUsingPivotTables=p.AllowUsingPivotTables)
    ws.Unprotect(PWD)
    return opts


def patch(wb):
    ws = wb.Worksheets(SRC)
    opts = unprotect(ws)
    done, skipped = 0, []
    for col, (old, new, note) in HEADERS.items():
        c = ws.Range(f"{col}2")
        cur = str(c.Value or "").strip()
        if cur not in (old, new):
            skipped.append(f"{col}: «{cur}»")
            continue
        if cur != new:
            c.Value = new
            done += 1
        if c.Comment is not None:
            c.Comment.Delete()
        if note:
            cm = c.AddComment(note)
            cm.Shape.TextFrame.AutoSize = True
    ws.Range("A2:CA2").WrapText = True
    if opts:
        ws.Protect(PWD, **opts)
    return done, skipped


def run(paths):
    app, pid = excel()
    try:
        for path in paths:
            wb = app.Workbooks.Open(os.path.abspath(path), 0, False)
            try:
                done, skipped = patch(wb)
                wb.Save()
                msg = f"{os.path.basename(path)}: заголовков изменено {done}"
                if skipped:
                    msg += "; не тронуты (там свой текст): " + ", ".join(skipped)
                print(msg)
            finally:
                wb.Close(False)
    finally:
        try:
            app.Quit()
        except Exception:
            pass
        subprocess.run(["taskkill", "/PID", str(pid), "/F"], capture_output=True)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    run(sys.argv[1:])
