C_TITLE = 6299648      # тёмно-синий (BGR)
C_SEC = 14857357       # голубой
C_HEADROW = 14277081
C_WARN = 13551615      # красноватый
C_CAUT = 10284031      # жёлтый
C_NOTE = 15921906      # светло-серый


def build(wb):
    old = sheet(wb, GUIDE)
    if old is not None:
        old.Delete()
    ws = wb.Worksheets.Add(Before=wb.Worksheets(1))
    ws.Name = GUIDE
    ws.Tab.Color = 5287936           # зелёный
    ws.Cells.Font.Name = "Arial"
    ws.Cells.Font.Size = 10
    ws.Columns("A").ColumnWidth = 8
    ws.Columns("B").ColumnWidth = 34
    ws.Columns("C").ColumnWidth = 80
    ws.Columns("D").ColumnWidth = 24
    ws.Cells.VerticalAlignment = -4160          # верх
    r = 1
    for item in G:
        k = item[0]
        if k == "T":
            c = ws.Range("A%d" % r)
            c.Value = item[1]
            c.Font.Size = 16
            c.Font.Bold = True
            c.Font.Color = C_TITLE
            ws.Rows(r).RowHeight = 24
        elif k == "S":
            r += 1
            rng = ws.Range("A%d:D%d" % (r, r))
            rng.Interior.Color = C_SEC
            ws.Range("A%d" % r).Value = item[1]
            ws.Range("A%d" % r).Font.Bold = True
            ws.Range("A%d" % r).Font.Size = 12
        elif k in ("P", "W", "C", "I"):
            rng = ws.Range("A%d:D%d" % (r, r))
            rng.Merge()
            rng.WrapText = True
            pre = {"P": "", "W": "ОСТОРОЖНО: ", "C": "ВНИМАНИЕ: ", "I": "ПРИМЕЧАНИЕ: "}[k]
            rng.Value = pre + item[1]
            if k == "W":
                rng.Interior.Color = C_WARN
                rng.Font.Bold = True
            elif k == "C":
                rng.Interior.Color = C_CAUT
            elif k == "I":
                rng.Interior.Color = C_NOTE
                rng.Font.Italic = True
            n = len(rng.Value)
            ws.Rows(r).RowHeight = 13.5 * max(1, -(-n // 115))
        elif k == "N":
            ws.Range("A%d" % r).Value = "'" + item[1]
            ws.Range("A%d" % r).Font.Bold = True
            t = ws.Range("B%d:C%d" % (r, r))
            t.Merge()
            t.WrapText = True
            t.Value = item[2]
            ws.Rows(r).RowHeight = 13.5 * max(1, -(-len(item[2]) // 105))
            link(ws, r, item[3])
        elif k in ("H", "R"):
            ws.Range("B%d" % r).Value = item[1]
            ws.Range("C%d" % r).Value = item[2]
            ws.Range("B%d:C%d" % (r, r)).WrapText = True
            if k == "H":
                h = ws.Range("B%d:D%d" % (r, r))
                h.Interior.Color = C_HEADROW
                h.Font.Bold = True
            else:
                link(ws, r, item[3])
                ws.Rows(r).RowHeight = 13.5 * max(1, -(-len(item[2]) // 80), -(-len(item[1]) // 34))
            for i in (7, 8, 9, 10, 11, 12):
                ws.Range("B%d:D%d" % (r, r)).Borders(i).LineStyle = 1
        r += 1
    try:
        ws.PageSetup.Orientation = 1
        ws.PageSetup.Zoom = False
        ws.PageSetup.FitToPagesWide = 1
        ws.PageSetup.FitToPagesTall = False
    except Exception:
        pass                           # нет принтера - печать не настраиваем
    ws.Activate()
    try:
        ws.Application.ActiveWindow.DisplayGridlines = False
        ws.Application.ActiveWindow.ScrollRow = 1
    except Exception:
        pass
    return r


def link(ws, r, target):
    if not target:
        return
    c = ws.Range("D%d" % r)
    shown = target.replace("'", "").replace("!", " → ")
    ws.Hyperlinks.Add(Anchor=c, Address="", SubAddress=target, TextToDisplay=shown)
    c.Font.Size = 9


def note_in_quick(wb):
    """строка-ссылка в «Краткое руководство» (первая пустая строка столбца A/B после правил)."""
    ws = sheet(wb, "Краткое руководство")
    if ws is None:
        return
    for r in range(2, 60):
        b = ws.Range("B%d" % r).Value
        if isinstance(b, str) and b.startswith("ПОЛНЫЙ ГАЙД"):
            return
        if ws.Range("A%d" % r).Value in (None, "") and (b in (None, "")):
            prev = ws.Range("A%d" % (r - 1)).Value
            try:
                ws.Range("A%d" % r).Value = int(prev) + 1
            except (TypeError, ValueError):
                pass
            ws.Range("A%d:B%d" % (r - 1, r - 1)).Copy()
            ws.Range("A%d:B%d" % (r, r)).PasteSpecial(-4122)
            ws.Application.CutCopyMode = False
            ws.Range("B%d" % r).Value = "ПОЛНЫЙ ГАЙД: лист «Гайд» (первый лист книги) — порядок работы, что и где вводить, проверка, неисправности."
            ws.Range("B%d" % r).Font.Bold = True
            return


def run(path):
    with ExcelSession() as xl:
        wb = xl.Workbooks.Open(os.path.abspath(path), 0, False)
        try:
            n = build(wb)
            note_in_quick(wb)
            wb.Save()
            log("гайд: %d строк — %s" % (n, os.path.basename(path)))
        finally:
            wb.Close(False)


def to_md(path):
    out = []
    for item in G:
        k = item[0]
        if k == "T":
            out.append("# " + item[1] + "\n")
        elif k == "S":
            out.append("\n## " + item[1] + "\n")
        elif k == "P":
            out.append(item[1] + "\n")
        elif k in ("W", "C", "I"):
            out.append("> **%s** %s\n" % ({"W": "ОСТОРОЖНО:", "C": "ВНИМАНИЕ:", "I": "ПРИМЕЧАНИЕ:"}[k], item[1]))
        elif k == "N":
            out.append("%s. %s%s" % (item[1], item[2], ("  _(%s)_" % item[3].replace("'", "")) if item[3] else ""))
        elif k == "H":
            out.append("\n| %s | %s |\n|---|---|" % (item[1], item[2]))
        elif k == "R":
            out.append("| %s | %s |" % (item[1], item[2]))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out).replace("\n\n\n", "\n\n") + "\n")
    log("md:", path)


