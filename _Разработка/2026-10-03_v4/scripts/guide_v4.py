def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("books", nargs="*")
    ap.add_argument("--md")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    g.G = G
    for b in a.books:
        g.run(b)
    if a.md:
        g.to_md(a.md)


if __name__ == "__main__":
    main()
